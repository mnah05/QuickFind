import AppKit
import Combine

struct ClipboardEntry: Codable, Identifiable, Equatable {
    var id: UUID
    var text: String
    var copiedAt: Date
    var isPinned: Bool
}

@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    @Published private(set) var entries: [ClipboardEntry]
    @Published private(set) var notice: String?
    @Published var isPaused: Bool {
        didSet {
            UserDefaults.standard.set(isPaused, forKey: "clipboardPaused.v1")
            lastChangeCount = NSPasteboard.general.changeCount
        }
    }
    @Published var expiryDays: Int {
        didSet {
            UserDefaults.standard.set(expiryDays, forKey: "clipboardExpiryDays.v1")
            pruneExpired()
            persist()
        }
    }
    private var timer: Timer?
    private var lastChangeCount = -1

    private init() {
        if let data = UserDefaults.standard.data(forKey: "clipboardEntries.v1"),
           let saved = try? JSONDecoder().decode([ClipboardEntry].self, from: data) {
            entries = saved
        } else {
            entries = (UserDefaults.standard.stringArray(forKey: "clipboardHistory") ?? []).map {
                ClipboardEntry(id: UUID(), text: $0, copiedAt: Date(), isPinned: false)
            }
            UserDefaults.standard.removeObject(forKey: "clipboardHistory")
        }
        isPaused = UserDefaults.standard.bool(forKey: "clipboardPaused.v1")
        let savedExpiry = UserDefaults.standard.object(forKey: "clipboardExpiryDays.v1") as? Int ?? 30
        expiryDays = [0, 1, 7, 30].contains(savedExpiry) ? savedExpiry : 30
        pruneExpired()
        trimUnpinned()
        persist()
    }

    var items: [String] { entries.map(\.text) }

    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword")
    ]

    func startMonitoring() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.15, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                self?.readCurrentClipboard()
            }
        }
        self.timer = timer
        RunLoop.main.add(timer, forMode: .common)
        readCurrentClipboard()
    }

    func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
        lastChangeCount = NSPasteboard.general.changeCount - 1
        readCurrentClipboard()
    }

    func togglePin(_ id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[index].isPinned.toggle()
        pruneExpired()
        sortEntries()
        trimUnpinned()
        persist()
    }

    func isPinned(_ id: UUID) -> Bool {
        entries.first(where: { $0.id == id })?.isPinned ?? false
    }

    func clear() {
        entries = []
        notice = nil
        persist()
    }

    private func readCurrentClipboard() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChangeCount else { return }
        lastChangeCount = board.changeCount
        guard !isPaused else { return }
        if let types = board.types, types.contains(where: { Self.ignoredTypes.contains($0) }) {
            return
        }
        guard let text = board.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        guard text.utf8.count <= 200_000 else {
            notice = "This text is over 200 KB and wasn’t saved to history."
            return
        }
        notice = nil
        if let index = entries.firstIndex(where: { $0.text == text }) {
            entries[index].copiedAt = Date()
        } else {
            entries.append(ClipboardEntry(id: UUID(), text: text, copiedAt: Date(), isPinned: false))
        }
        pruneExpired()
        sortEntries()
        trimUnpinned()
        persist()
    }

    private func pruneExpired() {
        guard expiryDays > 0 else { return }
        let cutoff = Date().addingTimeInterval(-Double(expiryDays) * 24 * 60 * 60)
        entries.removeAll { !$0.isPinned && $0.copiedAt < cutoff }
    }

    private func sortEntries() {
        entries.sort {
            if $0.isPinned != $1.isPinned { return $0.isPinned }
            return $0.copiedAt > $1.copiedAt
        }
    }

    private func trimUnpinned() {
        let pinned = entries.filter(\.isPinned)
        let recent = entries.filter { !$0.isPinned }.prefix(30)
        entries = pinned + recent
    }

    private func persist() {
        sortEntries()
        if let data = try? JSONEncoder().encode(entries) {
            UserDefaults.standard.set(data, forKey: "clipboardEntries.v1")
        }
    }
}
